/* Salón Dorado · service worker
   - Siempre pide la última versión al servidor (así cada cambio se ve enseguida, sin esperar ni forzar recarga).
   - Si no hay internet, abre la última versión guardada.
   - Solo toca los archivos de la app (mismo sitio). Firebase y los datos no pasan por acá. */
const CACHE = 'salon-dorado-v1';
self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', e => e.waitUntil(
  caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())
));
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  e.respondWith(
    fetch(req, { cache: 'no-cache' })
      .then(res => {
        if (res.ok) { const copia = res.clone(); caches.open(CACHE).then(c => c.put(req, copia)); }
        return res;
      })
      .catch(() => caches.match(req, { ignoreSearch: true }).then(r => r || caches.match('./index.html')))
  );
});
